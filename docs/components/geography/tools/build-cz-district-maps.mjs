#!/usr/bin/env node
/**
 * Generates templates/geography/cz-districts/{region}.html.twig from RÚIAN boundaries.
 * See docs/components/geography/rebuild.md for the full pipeline.
 *
 * Usage: node build-cz-district-maps.mjs <okresy.json> <praha-mop.json> <out-dir>
 *   okresy.json    – simplified okresy GeoJSON in EPSG:5514 (props: kod, nazev, vusc)
 *   praha-mop.json – simplified Praha městské obvody GeoJSON in EPSG:5514 (props: kod, nazev)
 */
import fs from 'node:fs';
import path from 'node:path';

const [okresyFile, mopFile, outDir] = process.argv.slice(2);
if (!okresyFile || !mopFile || !outDir) {
    console.error('Usage: node build-cz-district-maps.mjs <okresy.json> <praha-mop.json> <out-dir>');
    process.exit(1);
}

const VIEWBOX_WIDTH = 1000;
const PADDING = 10;

// RÚIAN VÚSC kód => region slug (same keys as cz-region-map.html.twig)
const REGIONS = {
    19: {slug: 'prazsky', name: 'Hlavní město Praha'},
    27: {slug: 'stredocesky', name: 'Středočeský kraj'},
    35: {slug: 'jihocesky', name: 'Jihočeský kraj'},
    43: {slug: 'plzensky', name: 'Plzeňský kraj'},
    51: {slug: 'karlovarsky', name: 'Karlovarský kraj'},
    60: {slug: 'ustecky', name: 'Ústecký kraj'},
    78: {slug: 'liberecky', name: 'Liberecký kraj'},
    86: {slug: 'kralovehradecky', name: 'Královéhradecký kraj'},
    94: {slug: 'pardubicky', name: 'Pardubický kraj'},
    108: {slug: 'vysocina', name: 'Kraj Vysočina'},
    116: {slug: 'jihomoravsky', name: 'Jihomoravský kraj'},
    124: {slug: 'olomoucky', name: 'Olomoucký kraj'},
    132: {slug: 'moravskoslezsky', name: 'Moravskoslezský kraj'},
    141: {slug: 'zlinsky', name: 'Zlínský kraj'},
};

const slugify = (s) => s
    .normalize('NFD').replace(/[̀-ͯ]/g, '')
    .toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

const polygonsOf = (geometry) => geometry.type === 'MultiPolygon' ? geometry.coordinates : [geometry.coordinates];

const read = (file) => JSON.parse(fs.readFileSync(file, 'utf8')).features;

const groups = {};
for (const f of read(okresyFile)) {
    (groups[f.properties.vusc] ??= []).push(f);
}
groups[19] = read(mopFile);

const twigString = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

fs.mkdirSync(outDir, {recursive: true});

for (const [vuscKod, features] of Object.entries(groups)) {
    const region = REGIONS[vuscKod];
    if (!region) {
        throw new Error(`Unknown VÚSC kód ${vuscKod}`);
    }

    // bbox in EPSG:5514 (x grows east, y grows north)
    let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
    for (const f of features) {
        for (const poly of polygonsOf(f.geometry)) {
            for (const [x, y] of poly[0]) {
                minX = Math.min(minX, x);
                maxX = Math.max(maxX, x);
                minY = Math.min(minY, y);
                maxY = Math.max(maxY, y);
            }
        }
    }
    const scale = (VIEWBOX_WIDTH - 2 * PADDING) / (maxX - minX);
    const height = Math.ceil((maxY - minY) * scale + 2 * PADDING);
    const px = (x) => +((x - minX) * scale + PADDING).toFixed(1);
    const py = (y) => +((maxY - y) * scale + PADDING).toFixed(1);

    const districts = features
        .map((f) => {
            const d = polygonsOf(f.geometry)
                .flatMap((poly) => poly)
                .map((ring) => {
                    const pts = ring.slice(0, -1).map(([x, y]) => `${px(x)} ${py(y)}`);
                    return `M${pts[0]}L${pts.slice(1).join(' ')}Z`;
                })
                .join('');
            const name = f.properties.nazev;
            return {slug: slugify(name), name, kod: f.properties.kod, d};
        })
        .sort((a, b) => a.name.localeCompare(b.name, 'cs', {numeric: true}));

    const slugs = new Set(districts.map((d) => d.slug));
    if (slugs.size !== districts.length) {
        throw new Error(`Duplicate district slug in ${region.slug}`);
    }

    const lines = [
        `{# GENERATED by docs/components/geography/tools/build-cz-district-maps.mjs – do not edit by hand #}`,
        `{# ${region.name}: ${districts.map((d) => d.slug).join(', ')} #}`,
        `{# Source: © ČÚZK, RÚIAN (CC BY 4.0) #}`,
        `{% include '@CmsBundle/geography/cz-districts/_svg.html.twig' with {`,
        `    region_name: ${twigString(region.name)},`,
        `    view_box: '0 0 ${VIEWBOX_WIDTH} ${height}',`,
        `    districts: [`,
        ...districts.map((d) => `        {slug: ${twigString(d.slug)}, name: ${twigString(d.name)}, code: '${d.kod}', d: '${d.d}'},`),
        `    ],`,
        `} %}`,
        ``,
    ];
    const file = path.join(outDir, `${region.slug}.html.twig`);
    fs.writeFileSync(file, lines.join('\n'));
    console.log(`${region.slug.padEnd(16)} ${String(districts.length).padStart(2)} districts  ${VIEWBOX_WIDTH}x${height}  ${(fs.statSync(file).size / 1024).toFixed(0)} kB`);
}
