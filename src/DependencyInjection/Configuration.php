<?php

namespace Sovic\Cms\DependencyInjection;

use Symfony\Component\Config\Definition\Builder\TreeBuilder;
use Symfony\Component\Config\Definition\ConfigurationInterface;

class Configuration implements ConfigurationInterface
{
    public function getConfigTreeBuilder(): TreeBuilder
    {
        $treeBuilder = new TreeBuilder('sovic_cms');

        $treeBuilder->getRootNode()
            ->children()
                ->scalarNode('base_public_url')
                    ->defaultValue('')
                    ->info('Base URL of the website, used when creating links from admin.')
                ->end()
                ->scalarNode('tinymce_content_css')
                    ->defaultValue('')
                    ->info('Custom CSS file URL loaded into the TinyMCE content editor.')
                ->end()
                ->arrayNode('gallery')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->scalarNode('base_url')
                            ->defaultValue('')
                            ->info('Base URL for public gallery files.')
                        ->end()
                        ->integerNode('upload_max_files')
                            ->defaultValue(25)
                            ->min(1)
                            ->info('Maximum number of files uploaded at once in admin gallery upload.')
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('page')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->booleanNode('enable_tags')
                            ->defaultFalse()
                            ->info('Show the tag field in the page edit form and the tags content type option.')
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('post')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->booleanNode('enable_tags')
                            ->defaultTrue()
                            ->info('Show the tag field in the post edit form.')
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('ai')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->scalarNode('components_dir')
                            ->defaultNull()
                            ->info('Directory with HTML component snippets, one *.html file per component (file name = component name). AI assistant is enabled when set.')
                        ->end()
                        ->scalarNode('styleguide_file')
                            ->defaultNull()
                            ->info('Markdown or HTML file describing the website styleguide.')
                        ->end()
                        ->scalarNode('model')
                            ->defaultValue('claude-opus-5')
                            ->info('Default Anthropic model, users can override it in their AI settings.')
                        ->end()
                        ->enumNode('effort')
                            ->values(['low', 'medium', 'high', 'xhigh', 'max'])
                            ->defaultValue('medium')
                            ->info('How much the model thinks before answering. Lower effort is faster and cheaper, higher gives better results on complex pages.')
                        ->end()
                        ->arrayNode('preview_css')
                            ->info('CSS files loaded into the assistant preview so generated content looks like the public website. URLs, absolute or relative to base_public_url. Falls back to tinymce_content_css.')
                            ->beforeNormalization()
                                ->ifString()
                                    ->then(static fn($value) => [$value])
                            ->end()
                            ->scalarPrototype()->end()
                            ->defaultValue([])
                        ->end()
                        ->scalarNode('preview_body_class')
                            ->defaultValue('')
                            ->info('Class attribute of the <body> element in the preview, when the website styles need it.')
                        ->end()
                        ->scalarNode('preview_wrapper_class')
                            ->defaultValue('')
                            ->info('Class of a wrapper <div> around the content in the preview, e.g. the container class of the public page template.')
                        ->end()
                        ->integerNode('max_tokens')
                            ->defaultValue(16000)
                            ->min(1024)
                            ->info('Max output tokens of one assistant response.')
                        ->end()
                        ->integerNode('history_limit')
                            ->defaultValue(20)
                            ->min(0)
                            ->info('Max number of previous conversation messages sent to the model.')
                        ->end()
                    ->end()
                ->end()
            ->end();

        return $treeBuilder;
    }
}
